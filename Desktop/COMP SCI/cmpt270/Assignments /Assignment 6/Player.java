public class Player {

    /**
     * the effect from drinking a FailedPotion
     */
    public void nothingEffect()
    {

        System.out.println("Potion didnt work...");
    }

    /**
     * the effect from drinking a BerryApple potion
     */
    public void invisibilityEffect() {
        System.out.println("You are invisible...");
    }

  /**
     * the effect from drinking a GrapeApple potion
     */
    public void speedEffect() {
        System.out.println("You have super speed...");
    }

    /**
     * the effect from drinking a LemonBerry potion
     */
    public void acidEffect() {
        System.out.println("You can manipulate acid...");
    }

}
